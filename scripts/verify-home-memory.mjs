import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const base = process.env.HOME_TEST_URL || 'http://127.0.0.1:4321/home/index.html';
const browser = await chromium.launch({channel:'chrome',headless:true});
try {
  const context = await browser.newContext({viewport:{width:1440,height:900},deviceScaleFactor:2});
  const page = await context.newPage();
  const errors = [], requests=[];
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', r => requests.push(r.url()));
  await page.route('**/bundle.19793ffb1086fd2d.js*',async route=>{
    const response=await route.fetch();
    const body=(await response.text()).replace('new Jf(document.querySelector(".webgl"))','window.__homeTest=new Jf(document.querySelector(".webgl"))');
    await route.fulfill({response,body});
  });
  await page.addInitScript(()=>{
    window.__webglContexts=0;
    const original=HTMLCanvasElement.prototype.getContext;
    HTMLCanvasElement.prototype.getContext=function(type,...args){
      if(type.startsWith('webgl')||type==='experimental-webgl')window.__webglContexts++;
      return original.call(this,type,...args);
    };
  });
  await page.goto(base);
  await page.waitForTimeout(3000);
  assert.equal(await page.evaluate(()=>window.__webglContexts),0);
  assert.equal(requests.some(url=>/bundle\.|home\.glb/.test(url)),false);
  if(process.env.HOME_TEST_SHOTS) await page.screenshot({path:process.env.HOME_TEST_SHOTS+'/welcome.png'});
  await page.locator('#enter-button').click();
  await page.waitForFunction(()=>window.__homeTest?.started,{timeout:30000});
  await page.waitForTimeout(6000);
  const snapshot=()=>page.evaluate(()=>({frame:window.__homeTest.renderer.info.render.frame,memory:window.__homeTest.renderer.info.memory,pixels:document.querySelector('canvas').width*document.querySelector('canvas').height}));
  const first=await snapshot();
  await page.waitForTimeout(3000);
  assert.equal((await snapshot()).frame,first.frame,'Idle scene must not render');
  assert.ok(first.pixels<=1500000);
  await page.locator('#theme-toggle').click();
  await page.waitForTimeout(500);
  const moodFrame=(await snapshot()).frame;
  await page.waitForTimeout(500);
  assert.ok((await snapshot()).frame>moodFrame,'Mood transition must keep rendering');
  await page.waitForTimeout(1200);
  assert.ok((await snapshot()).frame>first.frame,'Mood change must render');
  await page.locator('[data-room="study"]').click();
  await page.waitForTimeout(2500);
  assert.equal(await page.locator('#room-card').isVisible(),true);
  await page.locator('#home-view').click();
  await page.waitForTimeout(2000);
  await page.locator('#rotate-toggle').click();
  const rotating=await snapshot();
  await page.waitForTimeout(1500);
  assert.ok((await snapshot()).frame>rotating.frame);
  await page.locator('#rotate-toggle').click();
  await page.waitForTimeout(2000);
  // Exercise persisted lifecycle without relying on headless tab visibility.
  await page.evaluate(()=>dispatchEvent(new PageTransitionEvent('pagehide',{persisted:true})));
  const paused=await snapshot();await page.waitForTimeout(1000);
  assert.equal((await snapshot()).frame,paused.frame);
  await page.evaluate(()=>dispatchEvent(new PageTransitionEvent('pageshow',{persisted:true})));
  await page.waitForTimeout(1000);
  assert.ok((await snapshot()).frame>paused.frame);
  await page.setViewportSize({width:3840,height:2160});await page.waitForTimeout(1500);
  assert.ok((await snapshot()).pixels<=1500000,'4K viewport must respect pixel budget');
  await page.setViewportSize({width:1440,height:900});await page.waitForTimeout(1500);
  if(process.env.HOME_TEST_SHOTS)await page.screenshot({path:process.env.HOME_TEST_SHOTS+'/entered.png'});
  const idle=await snapshot();await page.waitForTimeout(15000);
  const end=await snapshot();assert.equal(end.frame,idle.frame);assert.deepEqual(end.memory,idle.memory);
  await page.evaluate(()=>window.__homeTest.dispose());
  assert.equal(await page.evaluate(()=>window.__homeTest.renderer.getContext().isContextLost()),true);
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({result:'PASS',welcomeWebGL:0,idle,after15Seconds:end,checks:['lazy entry','idle render suspension','day/night','room navigation','rotation','persisted lifecycle','4K pixel cap','dispose']}));
} finally {await browser.close();}
